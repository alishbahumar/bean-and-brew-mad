// Downloads every menu photo onto your laptop, so the app shows them from its own files
// (no internet needed on the phone, they can never fail to load).
// Run it with:  npm run photos      then restart the app with:  npx expo start -c
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const sources = JSON.parse(fs.readFileSync(path.join(root, 'src/data/photo-sources.json'), 'utf8'));
const dir = path.join(root, 'assets/images/menu');
fs.mkdirSync(dir, { recursive: true });

const items = { ...sources.products, hero: sources.hero, auth: sources.auth, cafe: sources.cafe };
const EXT = { 'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp' };
const existing = (key) => fs.readdirSync(dir).find((f) => f.startsWith(`${key}.`) && /\.(jpg|png|webp)$/.test(f));
const failed = [];

// Backup keyword search (real Flickr photos). Used only if the main link for an item fails.
const KEYWORDS = {
  espresso: 'espresso,coffee', americano: 'americano,coffee', cappuccino: 'cappuccino', latte: 'latte,coffee',
  mocha: 'mocha,coffee', 'flat-white': 'flatwhite,coffee', macchiato: 'macchiato,coffee', 'iced-latte': 'icedcoffee,latte',
  'cold-brew': 'coldbrew,coffee', frappe: 'frappe,coffee', 'iced-americano': 'icedcoffee', 'iced-matcha': 'matcha,iced',
  chai: 'chai,tea', kashmiri: 'pink,tea', 'matcha-latte': 'matcha,latte', croissant: 'croissant', 'almond-croissant': 'croissant,almond',
  brownie: 'brownie,chocolate', cookie: 'chocolate,cookie', 'double-choc-cookie': 'chocolate,cookies', 'blueberry-muffin': 'blueberry,muffin',
  hero: 'coffee,cafe', auth: 'coffee,beans', cafe: 'cafe,interior',
};
async function grab(url) {
  const res = await fetch(url, {
    redirect: 'follow',
    headers: { 'User-Agent': 'BeanAndBrewStudentApp/1.0 (university project)', Accept: 'image/*' },
  });
  const type = (res.headers.get('content-type') || '').split(';')[0].trim();
  if (!res.ok || !EXT[type]) throw new Error(`HTTP ${res.status}, type "${type}"`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 5000) throw new Error(`file too small (${buf.length} bytes)`);
  return { buf, type };
}

for (const [key, url] of Object.entries(items)) {
  if (existing(key)) {
    console.log(`= ${key} (already downloaded)`);
    continue;
  }
  const wide = ['hero', 'auth', 'cafe'].includes(key);
  const backup = `https://loremflickr.com/${wide ? '1200/900' : '800/800'}/${KEYWORDS[key] ?? 'coffee'}`;
  let done = false;
  let lastError = '';
  for (const link of [url, url]) {
    try {
      const { buf, type } = await grab(link);
      fs.writeFileSync(path.join(dir, `${key}.${EXT[type]}`), buf);
      console.log(`+ ${key}  (${Math.round(buf.length / 1024)} KB)${link === backup ? '' : ''}`);
      done = true;
      break;
    } catch (e) {
      lastError = e.message;
    }
  }
  if (!done) {
    failed.push(key);
    console.log(`x ${key}  FAILED: ${lastError}`);
  }
}

// Stand-ins: if an item's own photo could not be downloaded, copy the photo of a similar item.
// (Replace them any time by saving your own <item-id>.jpg in assets/images/menu and running npm run photos.)
const SUBSTITUTES = {
  americano: 'espresso',
  'iced-matcha': 'matcha-latte',
  kashmiri: 'chai',
  croissant: 'almond-croissant',
  'blueberry-muffin': 'cookie',
};
for (const key of [...failed]) {
  const from = SUBSTITUTES[key] && existing(SUBSTITUTES[key]);
  if (from && !existing(key)) {
    fs.copyFileSync(path.join(dir, from), path.join(dir, `${key}${path.extname(from)}`));
    console.log(`~ ${key}  uses the photo of ${SUBSTITUTES[key]} for now`);
    failed.splice(failed.indexOf(key), 1);
  }
}

// Write src/data/localPhotos.ts with a require() line for every photo file that exists.
const lines = Object.keys(items)
  .map((key) => [key, existing(key)])
  .filter(([, file]) => file)
  .map(([key, file]) => `  '${key}': require('../../assets/images/menu/${file}'),`);
fs.writeFileSync(
  path.join(root, 'src/data/localPhotos.ts'),
  `// AUTO-GENERATED by scripts/download-photos.mjs (npm run photos). Do not edit by hand.\n` +
    `export const LOCAL_PHOTOS: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);

console.log(`\nDone: ${lines.length} of ${Object.keys(items).length} photos are saved inside the app.`);
if (failed.length) {
  console.log(`Failed: ${failed.join(', ')}`);
  console.log('Send me this list. For each failed item you can also save your own photo as');
  console.log('assets/images/menu/<item-name>.jpg and run  npm run photos  again.');
}
